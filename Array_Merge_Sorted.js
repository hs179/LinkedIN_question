function fn(arr1, arr2){
    return [...arr1, ...arr2].sort((a,b) => a -b)
}



console.log(fn([1, 3, 5], [2, 4, 6]));                        // [1, 2, 3, 4, 5, 6]
console.log(fn([1, 2, 3], [4, 5, 6]));                        // [1, 2, 3, 4, 5, 6]
console.log(fn([], [1, 2, 3]));                               // [1, 2, 3]
console.log(fn([1, 2, 3], []));                               // [1, 2, 3]
console.log(fn([], []));                                      // []
console.log(fn([1], [2]));                                    // [1, 2]
console.log(fn([5, 10, 15], [3, 7, 12]));                     // [3, 5, 7, 10, 12, 15]
console.log(fn([-5, 0, 5], [-10, -3, 3]));                    // [-10, -5, -3, 0, 3, 5]
console.log(fn([1, 3, 5, 7], [2, 4, 6, 8]));                  // [1, 2, 3, 4, 5, 6, 7, 8]
console.log(fn([10, 20, 30], [5, 15, 25, 35]));               // [5, 10, 15, 20, 25, 30, 35]